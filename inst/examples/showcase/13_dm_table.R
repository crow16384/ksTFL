# Переменная modelval намерянно вынесена в отдельную колонку для демонстрации возможностей
# SECORD1 - порядковый номер группы, для демонстрации ручного разбиения на страницы

#CAT1          CAT2                     RPH104        PLCB          TOTAL         modelval SECTORD1
#<chr>         <chr>                    <chr>         <chr>         <chr>         <chr>       <dbl>
# 1 Возраст (лет) n                        "16"          "17"          "33"          NA              1
